/**
 * 상관 표의 칸 색 — docs/11-ui-guide.md §1.1
 *
 * 상관은 −1에서 +1이고 **0이 의미 있는 가운데**다. 단색 계열을 쓰면 강한 음의
 * 상관이 그냥 "낮은 값"으로 보인다. 그래서 양쪽으로 갈라지는 색을 쓴다.
 *
 *   −1 ─────── 0 ─────── +1
 *   테라코타   흐린 모래  청회색
 *
 * 성향 눈금과 같은 두 색을 쓰되 **방향이 반대**다. 저쪽은 낮음이 청회색,
 * 여기는 음의 관계가 테라코타다. 음의 관계를 따뜻한 색으로 두는 것이
 * 통계 도구의 관행이라 그쪽을 따랐고, 표 아래 범례에 방향을 적어 둔다.
 *
 * ## 가운데 색을 배경과 붙여 두지 않는다
 *
 * 처음에는 가운데를 `#e8e5dd`로 뒀는데, 이게 배경(`#f5f4f0`)과 거의 같은
 * 색이라 **0 근처 칸이 빈 칸처럼 보였다.** 이 표에는 진짜로 빈 칸이 따로
 * 있다 — 연구된 적 없음(`—`)과 관련 없음(`없음`)이다. 값이 있는데 0에
 * 가까운 칸과 값이 아예 없는 칸이 같아 보이면 표를 잘못 읽게 된다.
 *
 * 그래서 가운데를 배경보다 한 단 어둡게 내리고, 0에 붙어도 색이 남도록
 * 바닥을 깐다. 값이 있는 칸은 **언제나 칠해져 있다.**
 */

const NEG = [0xb3, 0x62, 0x3f]; // #b3623f 테라코타
const MID = [0xea, 0xe6, 0xde]; // #eae6de 흐린 모래 — 배경(#f5f4f0)보다 반 단 아래
const POS = [0x3a, 0x5f, 0xa0]; // #3a5fa0 청색 — 채도 하한을 통과하는 값 (11 §1.1)

/*
  ── 색 세기를 **등급 경계에 맞춘다** (2026-08-24) ──

  전에는 |r|을 0~0.7에 선형으로 폈다. 그런데 실제 값이 대부분 .5 아래에
  몰려 있어서 **쓰이는 구간이 좁았다** — .12짜리 칸과 .38짜리 칸이 거의
  같은 색으로 보였다.

  지금은 등급 경계(.10 / .20 / .30 / .50, 11 §3.5)마다 색이 한 단씩 올라가게
  꺾어 둔다. 색과 등급이 **같은 이야기**를 하게 되고, 값이 몰려 있어도
  칸끼리 갈린다.

      |r|   0    .10   .20   .30   .50+
      섞임  .05  .14   .24   .34   .46
            없음 약함  어느정도 뚜렷 매우뚜렷

  가장 진한 .46에서도 본문 잉크와 6:1 넘게 벌어진다 — 칸 안 글자가 읽힌다.
*/
const STOPS: [number, number][] = [
  [0, 0.05],
  [0.1, 0.14],
  [0.2, 0.24],
  [0.3, 0.34],
  [0.5, 0.46],
];

function mixFor(absR: number): number {
  for (let i = 1; i < STOPS.length; i++) {
    const [r1, m1] = STOPS[i - 1];
    const [r2, m2] = STOPS[i];
    if (absR > r2) continue;
    const t = r2 === r1 ? 0 : (absR - r1) / (r2 - r1);
    return m1 + (m2 - m1) * t;
  }
  return STOPS[STOPS.length - 1][1];
}

/**
 * @param faded 방향이 확정되지 않은 칸(신뢰구간이 0을 걸침)을 옅게 만든다.
 *   **투명도를 쓰지 않는다.** `opacity`를 걸면 칸 안의 글자까지 같이 흐려져
 *   읽을 수 없게 된다. 색만 가운데 쪽으로 되돌린다.
 */
export function correlationFill(r: number, faded = false): string {
  const end = r < 0 ? NEG : POS;
  let k = mixFor(Math.abs(r));
  if (faded) k *= 0.45;
  const mix = MID.map((m, i) => Math.round(m + (end[i] - m) * k));
  return `rgb(${mix.join(" ")})`;
}

/** 소수 둘째 자리, 앞의 0 생략, 부호 항상 — `+.28` (11 §3.2) */
export function formatR(r: number): string {
  return (r < 0 ? "−" : "+") + Math.abs(r).toFixed(2).replace(/^0/, "");
}
