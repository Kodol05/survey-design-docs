/**
 * 상관 표의 칸 색 — docs/11-ui-guide.md §1.1
 *
 * 상관은 −1에서 +1이고 **0이 의미 있는 가운데**다. 단색 계열을 쓰면 강한 음의
 * 상관이 그냥 "낮은 값"으로 보인다. 그래서 양쪽으로 갈라지는 색을 쓴다.
 *
 *   −1 ─────── 0 ─────── +1
 *   테라코타   흐린 모래  청회색
 *
 * 성향 눈금과 같은 두 색을 쓰되 **방향이 반대**다. 저쪽은 낮음이 청회색,
 * 여기는 음의 관계가 테라코타다. 음의 관계를 따뜻한 색으로 두는 것이
 * 통계 도구의 관행이라 그쪽을 따랐고, 표 아래 범례에 방향을 적어 둔다.
 *
 * ## 가운데 색을 배경과 붙여 두지 않는다
 *
 * 처음에는 가운데를 `#e8e5dd`로 뒀는데, 이게 배경(`#f5f4f0`)과 거의 같은
 * 색이라 **0 근처 칸이 빈 칸처럼 보였다.** 이 표에는 진짜로 빈 칸이 따로
 * 있다 — 연구된 적 없음(`—`)과 관련 없음(`없음`)이다. 값이 있는데 0에
 * 가까운 칸과 값이 아예 없는 칸이 같아 보이면 표를 잘못 읽게 된다.
 *
 * 그래서 가운데를 배경보다 한 단 어둡게 내리고, 0에 붙어도 색이 남도록
 * 바닥을 깐다. 값이 있는 칸은 **언제나 칠해져 있다.**
 */

/*
  색을 **숫자로 박지 않고 CSS 토큰으로 섞는다** (2026-08-24).

  전에는 rgb 값을 상수로 두고 자바스크립트에서 섞었다. 그러면 다크 모드에서
  같이 못 바뀐다 — 어두운 바탕에 밝은 곳 색을 그대로 깔게 된다.

  `color-mix`는 브라우저가 그릴 때 계산하므로 `--diverge-*` 토큰이 테마마다
  달라지면 **알아서 따라온다.** 섞는 비율만 우리가 정한다.
*/

/*
  ── 색 세기를 **등급 경계에 맞춘다** (2026-08-24) ──

  전에는 |r|을 0~0.7에 선형으로 폈다. 그런데 실제 값이 대부분 .5 아래에
  몰려 있어서 **쓰이는 구간이 좁았다** — .12짜리 칸과 .38짜리 칸이 거의
  같은 색으로 보였다.

  지금은 등급 경계(.10 / .20 / .30 / .50, 11 §3.5)마다 색이 한 단씩 올라가게
  꺾어 둔다. 색과 등급이 **같은 이야기**를 하게 되고, 값이 몰려 있어도
  칸끼리 갈린다.

      |r|   0    .10   .20   .30   .50+
      섞임  .05  .14   .24   .34   .46
            없음 약함  어느정도 뚜렷 매우뚜렷

  가장 진한 .46에서도 본문 잉크와 6:1 넘게 벌어진다 — 칸 안 글자가 읽힌다.
*/
const STOPS: [number, number][] = [
  [0, 0.05],
  [0.1, 0.14],
  [0.2, 0.24],
  [0.3, 0.34],
  [0.5, 0.46],
];

function mixFor(absR: number): number {
  for (let i = 1; i < STOPS.length; i++) {
    const [r1, m1] = STOPS[i - 1];
    const [r2, m2] = STOPS[i];
    if (absR > r2) continue;
    const t = r2 === r1 ? 0 : (absR - r1) / (r2 - r1);
    return m1 + (m2 - m1) * t;
  }
  return STOPS[STOPS.length - 1][1];
}

/**
 * @param faded 방향이 확정되지 않은 칸(신뢰구간이 0을 걸침)을 옅게 만든다.
 *   **투명도를 쓰지 않는다.** `opacity`를 걸면 칸 안의 글자까지 같이 흐려져
 *   읽을 수 없게 된다. 색만 가운데 쪽으로 되돌린다.
 */
export function correlationFill(r: number, faded = false): string {
  const end = r < 0 ? "var(--diverge-neg)" : "var(--diverge-pos)";
  let k = mixFor(Math.abs(r));
  if (faded) k *= 0.45;
  return `color-mix(in oklab, ${end} ${(k * 100).toFixed(1)}%, var(--diverge-mid))`;
}

/**
 * 상관 막대가 **끝까지 차는 값**.
 *
 * ## 왜 1.00 인가 (2026-08-26 사용자 지적으로 바로잡음)
 *
 * 전에는 `0.7`이었다. 「실제 데이터에서 |r|이 1에 가는 일은 없다」는 이유였다.
 * 그런데 그 판단은 **그때 화면에 있던 값(최대 0.59)에 맞춘 것**이었다.
 *
 * ⚠️ 실제로 넘는 값이 이미 있었다 — 평가 대조의 본인↔대표님 상관은
 * **0.95 · 0.85 · 0.80**이다. 0.7 눈금에서는 `Math.min`에 걸려 셋이 **똑같이
 * 꽉 찬 막대**로 보인다. 넘쳤다는 말도 없이 조용히 잘린다.
 *
 * 상관은 −1에서 +1 사이라는 것이 정의다. 눈금을 거기 맞추면 **어떤 데이터가
 * 와도 잘리지 않고**, 오늘 값이 얼마냐와 무관해진다. 화면 타일에 적어 둔
 * 「0.00 관계 없음 → 1.00」과도 같은 말이 된다.
 *
 * 대신 흔한 크기(0.2~0.6)의 막대가 짧아진다. 그건 **사실 그대로**다 —
 * 0.3짜리 관계를 0.7 눈금으로 크게 보이게 하던 쪽이 과장이었다.
 *
 * ⚠️ 세 군데에 따로 적혀 있던 것을 여기로 모았다 (`TopRelations` ·
 * `CorrelationTable` · `DivergingBar`). 하나만 고치면 화면마다 다른 눈금이 된다.
 */
export const CORR_FULL = 1;

/*
  ── 0과 1 사이 값을 적는 법 (2026-08-26 사용자 요청으로 바로잡음) ──

  **앞의 0을 적는다.** `+0.73`, `0.94`.

  전에는 `+.73`처럼 생략했다. 논문 표기 관습이고, 읽는 사람이 「r은 −1에서
  +1 사이」라는 걸 이미 알고 있을 때만 통한다. **우리 화면을 보는 사람은
  연구자가 아니다.**

  ⚠️ 게다가 실제로 어긋나 있었다 — 「예측이 맞은 정도 `+.73`」 바로 옆
  타일에 「실제로 나타난 기울기 `0.73`」이 있었다. **같은 0.73인데 표기가
  다른 두 수가 나란히** 있었던 것이다. 생략 규칙이 다섯 군데에 복사돼
  있었고 기울기만 빠져 있었다.

  이제 이 파일이 그 규칙을 혼자 갖는다.
*/

/** 상관·기울기처럼 부호가 뜻을 갖는 값 — `+0.73` · `−0.56` */
export function formatR(r: number): string {
  return (r < 0 ? "−" : "+") + Math.abs(r).toFixed(2);
}

/** α처럼 0~1 사이에서 부호가 없는 값 — `0.94` */
export function formatRatio(v: number): string {
  return v.toFixed(2);
}
