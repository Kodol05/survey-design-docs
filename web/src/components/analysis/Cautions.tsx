import { Note } from "../ui/Note";

/**
 * 유의할 것을 **화면 맨 아래 한 곳에** 모은다 (2026-08-25 사용자 요청).
 *
 * ## 흩어져 있으면 아무도 안 읽는다
 *
 * 「이 척도는 아직 안정적이지 않습니다」, 「관련이 약하다가 아니라 아직 말할
 * 수 없다」, 「우연히 높게 나온 값이 섞여 있을 수 있습니다」 — 같은 뜻의
 * 경고가 표 아래, 능력마다, 명단 위에 흩어져 있었다. 세 번째부터는 눈이
 * 그냥 건너뛴다.
 *
 * ## 자리에는 표시만 남긴다
 *
 * 문장은 여기로 모으되, **그 자리에서 알아야 할 것**은 남긴다 —
 * 열 머리의 `α .08 · 기준 아래`, 흐린 칸의 빗금, 등급 옆의 `?`.
 * 표시는 「여기 뭔가 있다」를 말하고, 이 자리는 「그게 무슨 뜻인지」를
 * 말한다.
 */
export function Cautions({
  poor,
  facetCount,
}: {
  /** α가 기준 아래인 축 이름들 */
  poor: string[];
  /** 세부 항목을 몇 개나 훑는지 — 다중비교 경고에 쓴다 */
  facetCount?: number;
}) {
  return (
    <Note label="읽으실 때 유의할 것" className="mt-16">
      {poor.length > 0 && (
        <p className="mb-2">
          <strong>{poor.join(" · ")}</strong>는 문항끼리 맞물리지 않습니다
          (빗금 친 열). 잰 값에 잡음이 섞여 있어 상관이{" "}
          <strong>실제보다 작게</strong> 나옵니다 — 「관련이 약하다」가 아니라{" "}
          <strong>「아직 말할 수 없다」</strong>입니다. 사람이 늘어도 좋아지지
          않고 문항을 고쳐야 합니다.{" "}
          <a href="/admin/stats?tab=reliability" className="underline">
            신뢰도 보기
          </a>
        </p>
      )}
      <p className="mb-2">
        <strong>등급 옆의 「?」</strong>는 95% 구간이 0을 걸친다는 뜻입니다 —
        크기는 그만한데 <strong>방향이 아직 확정되지 않았습니다.</strong>{" "}
        40명 남짓에서는 흔한 일이라, 확정된 것부터 보시면 됩니다.
      </p>
      <p className="mb-2">
        <strong>가까운 값끼리는 순위를 가리지 마십시오.</strong> `.32`와 `.31`,
        13점과 11점은 다시 재면 뒤바뀝니다. 위쪽 무리와 아래쪽 무리를 가르는
        정도로만 보시는 것이 안전합니다.
      </p>
      {facetCount ? (
        <p>
          세부 항목까지 쪼개면 상관이{" "}
          <span className="tabular">{facetCount}</span>개가 됩니다.{" "}
          <strong>관계가 없어도 네댓 개는 우연히 높게</strong> 나오므로
          탐색용으로만 쓰십시오.
        </p>
      ) : (
        <p>
          <strong>여기 숫자는 관계이지 원인이 아닙니다.</strong> 인내력이 높은
          사람의 직무능력이 높게 나왔다고 해서 인내력을 올리면 직무능력이
          오른다는 뜻은 아닙니다.
        </p>
      )}
    </Note>
  );
}
