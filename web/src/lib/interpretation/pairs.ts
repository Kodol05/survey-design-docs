export const PAIR_SPLIT = 50;

export type AxisInput = { percent: number; band: "lower" | "middle" | "upper" };

export type PairReading = {
  pair: AxisPair;
  key: PairKey;
  text: string;
  /** 어느 쪽이라고 하기 어려운 축 */
  unclear: string[];
};

export function readPairs(scores: Record<string, AxisInput>): PairReading[] {
  const out: PairReading[] = [];
  for (const pair of PAIRS) {
    const a = scores[pair.a];
    const b = scores[pair.b];
    if (!a || !b) continue;
    const key = `${a.percent >= PAIR_SPLIT ? "H" : "L"}${
      b.percent >= PAIR_SPLIT ? "H" : "L"
    }` as PairKey;
    const unclear = [
      ...(a.band === "middle" ? [pair.a] : []),
      ...(b.band === "middle" ? [pair.b] : []),
    ];
    out.push({ pair, key, text: pair.text[key], unclear });
  }
  return out;
}
