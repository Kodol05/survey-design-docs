/**
 * ⚠️⚠️ **임시 가입 상한 — 밖에 열어 두고 시험하기 위한 것** (2026-08-26) ⚠️⚠️
 *
 * ## 왜 있나
 *
 * 이 시스템의 가입은 **자율 등록**이다 (D-25). 이름 + 전화번호 + 비밀번호면
 * 누구나 계정이 만들어지고 곧장 설문으로 들어간다. 사전 명단(`Roster`) 표가
 * 있지만 가입 자격 판정에는 일부러 쓰지 않는다.
 *
 * 그 결정은 **사내망 안**을 전제로 한 것이다. 밖에서 닿을 수 없으면 모르는
 * 사람이 들어올 길이 없다.
 *
 * 그런데 cloudflared 같은 것으로 **인터넷에 열어 두고 시험**하는 동안에는
 * 그 전제가 깨진다. 주소를 아는 사람이 계정을 만들고 120문항에 답하면 그
 * 답이 평균·상관·α·사내 위치에 **그대로 섞인다.** 지금 36명 기준이라 몇
 * 명만 들어와도 숫자가 흔들린다. 밖으로 새는 것이 아니라 **안으로 들어오는**
 * 문제다.
 *
 * ## 이건 제대로 된 방어가 아니다
 *
 * 그저 숫자 하나로 막아 둔 것이다. **200명 안쪽에서 들어오는 것은 못 막는다.**
 * 급한 대로 「폭주만 막는」 수준이라고 보면 된다.
 *
 * ## 사내 서버로 올린 뒤에 할 일
 *
 * 밖에서 닿을 수 없게 되면 **이 상한은 필요 없다.** 둘 중 하나를 하면 된다.
 *
 *   ① `SIGNUP_CAP`을 `null`로 두면 상한이 없어진다 (원래 D-25 그대로)
 *   ② 계속 밖에 열어 둘 것이라면 숫자가 아니라 **명단으로 막아야 한다** —
 *      `Roster`에 있는 번호만 가입되게. 그게 제대로 된 방어다.
 *
 * 회사가 50명 규모라 200이면 넉넉하다. 사람이 그보다 늘어난다면 그때는
 * ②를 해야 할 때다.
 */
export const SIGNUP_CAP: number | null = 200;

/**
 * 지금 인원으로 가입을 막아야 하는가.
 *
 * `actions.ts`는 `"use server"` 파일이라 **비동기 함수만 내보낼 수 있다.**
 * 그래서 판정을 여기 따로 둔다 — 덕분에 시험도 할 수 있다.
 */
export function signupFull(members: number): boolean {
  return SIGNUP_CAP !== null && members >= SIGNUP_CAP;
}

/**
 * 막혔을 때 하는 말.
 *
 * **몇 명인지도, 왜 막혔는지도 말하지 않는다.** 「200명이 차서」라고 적으면
 * 밖에서 회사 규모를 세는 실마리가 된다. 가입 실패가 「이미 있는 번호」인지
 * 「상한」인지도 구분되지 않아야 한다 — 구분되면 어떤 번호가 이미 쓰이는지
 * 알아낼 수 있다.
 */
export const SIGNUP_FULL_MESSAGE =
  "지금은 새로 가입할 수 없습니다. 관리자에게 문의해 주세요";
