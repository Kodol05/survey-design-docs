/**
 * 사내 상위 몇 % — 관리자 요약 장의 직무능력 옆 숫자 (2026-10-07 사용자 결정).
 *
 * ## 왜 숫자로 바꿨나
 *
 * 분포 위치는 원래 세 단계(아래쪽·가운데·위쪽, `distribution.ts`)로만 보였다.
 * 그런데 관리자 상세를 한 화면에 모으면서 「그래서 이 사람이 몇 등쯤인가」를
 * 바로 읽고 싶다는 요청이 나왔다. 세 단계는 서른 명 중 1등과 10등을 같은
 * 「위쪽」으로 묶는다. **관리자 화면에서만** 숫자로 보인다 — 개인 화면에는
 * 여전히 사내 위치를 두지 않는다 (D-09).
 *
 * ## 정의
 *
 *   모집단  이 사람 + 비교 대상(`others`, 이 사람을 뺀 응시 완료자)
 *   n       others.length + 1
 *   등수    1 + (이 사람보다 **높은** 점수의 수) — 같은 점수는 가장 좋은 등수를 함께 쓴다
 *   상위 %  ceil(등수 / n × 100)
 *
 * 그래서 혼자면 상위 100%, 마흔두 명 중 1등이면 상위 3%(2.38 → 올림),
 * 꼴찌는 상위 100%다. 0%는 나오지 않는다. 올림인 이유는 「상위 2%」라고
 * 적었을 때 실제로는 2.38%인 사람이 그 말을 넘겨 받지 않게 하려는 것이다 —
 * 좋게 반올림하지 않는다.
 *
 * 이 사람 자신을 `others`에 넣지 않는 이유 — 넣고 빼는 것을 부르는 쪽마다
 * 다르게 하면 n이 하나씩 어긋난다. 여기서 한 번만 더한다.
 */
export function topPercent(others: readonly number[], score: number): number {
  const valid = others.filter((v) => Number.isFinite(v));
  const n = valid.length + 1;
  const rank = 1 + valid.filter((v) => v > score).length;
  // 정수끼리 곱하고 나누므로 나눠떨어지는 경우 오차 없이 정수가 나온다
  return Math.ceil((rank * 100) / n);
}
